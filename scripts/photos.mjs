// Downloads the free-licence (Pexels licence, no attribution required) photos used in the app,
// resizes them and writes WebP files to public/photos so the desktop app works offline.
// Usage: node scripts/photos.mjs
import sharp from "sharp";
import { mkdirSync, writeFileSync } from "node:fs";

const PHOTOS = [
  ["hero-consultation", 39192358, 1600],
  ["consult-smile", 7579831, 1400],
  ["clinician-tablet", 19957221, 1400],
  ["clinician-portrait", 5452291, 1100],
  ["care-team", 5452193, 1100],
  ["colleagues", 6129657, 1400],
  ["pill-organizer", 8088903, 1100],
  ["meds-table", 6798554, 1400],
  ["walk-autumn", 34446701, 1100],
  ["walk-coat", 20127701, 1100],
  ["blossom", 21328000, 1100],
  ["waiting-room", 4266934, 1400],
];

mkdirSync("public/photos", { recursive: true });
const sizes = {};
for (const [name, id, width] of PHOTOS) {
  const url = `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=${width}`;
  const res = await fetch(url, { headers: { "user-agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const img = sharp(Buffer.from(await res.arrayBuffer()));
  const out = await img.resize({ width, withoutEnlargement: true }).webp({ quality: 72 }).toBuffer({ resolveWithObject: true });
  writeFileSync(`public/photos/${name}.webp`, out.data);
  sizes[name] = { w: out.info.width, h: out.info.height, kb: Math.round(out.data.length / 1024), pexels: id };
}
writeFileSync("src/lib/photos.ts", `/** Generated by scripts/photos.mjs. Pexels licence photos, stored locally. */\nexport const PHOTOS = ${JSON.stringify(sizes, null, 2)} as const;\nexport type PhotoName = keyof typeof PHOTOS;\n`);
console.table(sizes);
